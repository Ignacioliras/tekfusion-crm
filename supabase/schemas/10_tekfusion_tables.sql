--
-- TekFusion: types, tables and columns added on top of Atomic CRM (Fase 2).
-- Approved design: docs/fase-2-propuesta.md and docs/10-decisiones.md (2026-11-03).
-- Enum values are in Spanish on purpose: they are the same values the UI uses
-- (src/components/atomic-crm/tekfusion/estados.ts, lineas.ts) and the lead
-- classifier returns. Identifiers stay in English.
--

create type public.user_role as enum ('manager', 'executive', 'reader');
create type public.business_line as enum ('valvulas', 'tuberias', 'geoceldas', 'indeterminada');
create type public.origin_channel as enum ('correo', 'formulario', 'bot', 'whatsapp', 'manual', 'migracion');

-- Configuration tables (read by everyone, written by managers: 11_tekfusion_policies.sql).
create table public.lost_reasons (
    id bigint generated by default as identity primary key,
    name text not null unique,
    active boolean not null default true,
    position smallint not null default 0
);

create table public.business_lines (
    code public.business_line primary key check (code <> 'indeterminada'),
    name text not null,
    owner_sales_id bigint references public.sales (id),
    substitute_sales_id bigint references public.sales (id),
    keywords text[] not null default '{}'
);

create table public.sales_absences (
    id bigint generated by default as identity primary key,
    sales_id bigint not null references public.sales (id),
    starts_on date not null,
    ends_on date not null,
    reason text,
    constraint sales_absences_range check (ends_on >= starts_on)
);

-- sales (an "ejecutivo"): the role is the source of truth; `administrator`
-- is kept in sync so Atomic's screens keep recognizing managers (decision 2).
alter table public.sales
    add column role public.user_role not null default 'executive',
    add column whatsapp_phone text,
    add column signature text,
    add constraint sales_whatsapp_phone_e164 check (whatsapp_phone ~ '^\+[1-9][0-9]{7,14}$');

-- deals (a "lead")
alter table public.deals
    add column business_line public.business_line not null default 'indeterminada',
    add column ai_confidence numeric(3, 2),
    add column origin_channel public.origin_channel not null default 'manual',
    add column raw_source jsonb,
    add column first_response_at timestamp with time zone,
    add column last_activity_at timestamp with time zone not null default now(),
    add column lost_reason_id bigint references public.lost_reasons (id),
    add column won_amount bigint,
    add column previous_deal_id bigint references public.deals (id),
    add column followups_enabled boolean not null default true,
    add constraint deals_ai_confidence_range check (ai_confidence between 0 and 1),
    add constraint deals_won_amount_positive check (won_amount >= 0),
    -- Single source of truth for stages: estados.ts. Keep both in sync.
    add constraint deals_stage_check check (stage in ('nuevo', 'contactado', 'cotizado', 'ganado', 'perdido', 'archivado'));
-- "ganado requires won_amount" and "perdido requires lost_reason_id" come in
-- Fase 3 with the screens that ask for them.

alter table public.contacts
    add column do_not_contact boolean not null default false,
    add column anonymized_at timestamp with time zone;

-- RLS from day one: the policies live in 11_tekfusion_policies.sql.
alter table public.lost_reasons enable row level security;
alter table public.business_lines enable row level security;
alter table public.sales_absences enable row level security;

create index deals_sales_stage_idx on public.deals using btree (sales_id, stage);
create index deals_stage_created_idx on public.deals using btree (stage, created_at);
-- The contacts RLS looks contacts up inside deals.contact_ids.
create index deals_contact_ids_idx on public.deals using gin (contact_ids);

-- Keeps sales.role and sales.administrator consistent in both directions:
-- changing one updates the other, so Atomic's "Admin" switch still works and
-- the first user (administrator = true) becomes the manager.
CREATE OR REPLACE FUNCTION "public"."sync_sales_role"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'INSERT' then
    if new.administrator then
      new.role := 'manager';
    elsif new.role = 'manager' then
      new.administrator := true;
    end if;
  elsif new.role is distinct from old.role then
    new.administrator := (new.role = 'manager');
  elsif new.administrator is distinct from old.administrator then
    new.role := case
      when new.administrator then 'manager'::public.user_role
      when new.role = 'manager' then 'executive'::public.user_role
      else new.role
    end;
  end if;
  return new;
end;
$$;

create or replace trigger sync_sales_role_trigger
    before insert or update of role, administrator on public.sales
    for each row execute function public.sync_sales_role();
