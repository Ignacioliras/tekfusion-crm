);

-- Follow-up texts, edited by managers. Only the variables the sender knows
-- how to fill: {{nombre}}, {{empresa}}, {{producto}}, {{ejecutivo}}.
create table public.templates (
    id bigint generated by default as identity primary key,
    name text not null unique,
    channel public.send_channel not null,
    subject text,
    body text not null,
    active boolean not null default true,
    constraint templates_subject_email_only check (channel = 'correo' or subject is null),
    constraint templates_known_variables check (
        (coalesce(subject, '') || ' ' || body) !~ '\{\{(?!(nombre|empresa|producto|ejecutivo)\}\})'
    )
);

create table public.quick_replies (
    id bigint generated by default as identity primary key,
    title text not null unique,
    body text not null,
    active boolean not null default true
);

-- A quote is a PDF made outside the CRM (Excel) plus its amount; every change
-- is a new version. The PDF lives in the private bucket "quotes" under
-- deals/<deal_id>/<uuid>.pdf (name regenerated, docs/08). sales_id = author.
-- Never deleted (no delete policy nor grant).
create table public.quotes (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    deal_id bigint not null references public.deals (id) on delete restrict,
    version smallint not null,
    amount bigint not null,
    pdf_path text not null,
    is_current boolean not null default true,
    sent_at timestamp with time zone,
    sent_channels public.send_channel[] not null default '{}',
    delivery_status public.delivery_status not null default 'pendiente',
    sales_id bigint references public.sales (id) on delete restrict,
    constraint quotes_deal_version_key unique (deal_id, version),
    constraint quotes_version_positive check (version > 0),
    constraint quotes_amount_positive check (amount >= 0),
    constraint quotes_pdf_path_in_deal_folder check (pdf_path ~ ('^deals/' || deal_id || '/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.pdf$')),
    constraint quotes_sent_has_channel check (sent_at is null or cardinality(sent_channels) > 0)
);

-- One step of a lead's follow-up cadence. n8n sends the automatic ones and
-- alerts the executive for reminders; cancelling is an update, never a delete.
create table public.followups (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    deal_id bigint not null references public.deals (id) on delete restrict,
    step smallint not null,
    scheduled_at timestamp with time zone not null,
    channels public.send_channel[] not null,
    mode public.followup_mode not null default 'automatico',
    template_id bigint references public.templates (id) on delete restrict,
    status public.followup_status not null default 'pendiente',
    sent_at timestamp with time zone,
    -- n8n idempotency key: a retried run never sends twice.
    job_id text unique,
    attempts smallint not null default 0,
    cancel_reason text,
    constraint followups_step_positive check (step > 0),
    constraint followups_has_channel check (cardinality(channels) > 0),
    constraint followups_attempts_positive check (attempts >= 0),
    constraint followups_sent_at check (status <> 'enviado' or sent_at is not null),
    constraint followups_cancel_reason check (status = 'cancelado' or cancel_reason is null)
);

-- In-app alerts (the bell). Written by the system (n8n, service role); the
-- recipient only marks them read. deal_id is null for whatsapp_desconectado.
create table public.alerts (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    type public.alert_type not null,
    recipient_sales_id bigint not null references public.sales (id) on delete restrict,
    deal_id bigint references public.deals (id) on delete restrict,
    message text not null,
    read_at timestamp with time zone,
    whatsapp_sent_at timestamp with time zone
);

