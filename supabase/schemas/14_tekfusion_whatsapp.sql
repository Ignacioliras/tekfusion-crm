--
-- TekFusion WhatsApp tables (Fase 4, schema only). docs/05 (conversaciones,
-- mensajes, estado_whatsapp) and docs/07 (Receptor). Evolution -> Edge
-- Function (service role) -> these tables; n8n never stores messages.
-- RLS (docs/08): conversations and messages are read-only for logged-in users
-- (managers all; executives theirs and the unassigned ones; readers none) and
-- written only by the service role and its RPCs. wa_instance_status and
-- wa_message_payloads (raw webhook bodies) stay closed to every API role but
-- the service role; of the instance, users only get wa_connection_status().
-- Tests: supabase/tests/32_whatsapp_tablas, 34_wa_ingest, 35_rls_whatsapp,
-- 36_wa_rpc, 37_wa_cliente_respondio, 38_send_wa_message,
-- 39_wa_connection_status.
--

create type public.wa_direction as enum ('entrante', 'saliente');
create type public.wa_message_type as enum ('texto', 'imagen', 'documento', 'audio', 'video', 'otro');
create type public.wa_message_origin as enum ('crm', 'seguimiento', 'telefono');

-- One conversation per WhatsApp number. phone is E.164, or 'anon-<id>' once
-- its contact was anonymized (RF-17, anonymize_contact_data in 11_).
create table public.wa_conversations (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    phone text not null unique,
    contact_id bigint references public.contacts (id) on delete set null,
    active_deal_id bigint references public.deals (id) on delete set null,
    sales_id bigint references public.sales (id) on delete set null,
    last_message_at timestamp with time zone,
    unread_count integer not null default 0,
    archived boolean not null default false,
    constraint wa_conversations_phone_e164 check (phone ~ '^\+[1-9][0-9]{7,14}$' or phone ~ '^anon-[0-9]+$'),
    constraint wa_conversations_unread_count_positive check (unread_count >= 0)
);

-- wa_message_id is unique: webhook retries never create a second row (CLAUDE.md rule 2).
create table public.wa_messages (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    conversation_id bigint not null references public.wa_conversations (id) on delete restrict,
    deal_id bigint references public.deals (id) on delete set null,
    wa_message_id text not null unique,
    direction public.wa_direction not null,
    type public.wa_message_type not null,
    text text,
    attachment_path text,
    status public.delivery_status not null default 'pendiente',
    from_me_phone boolean not null default false,
    author_sales_id bigint references public.sales (id) on delete set null,
    origin public.wa_message_origin,
    job_id text unique,
    sent_at timestamp with time zone not null
);

-- Raw webhook body of a message (debugging, reconciliation). It carries what
-- Evolution adds to every event (instance apikey, server_url), so it lives
-- apart from wa_messages: no API role but the service role reads it (docs/10).
create table public.wa_message_payloads (
    message_id bigint primary key references public.wa_messages (id) on delete cascade,
    payload jsonb not null
);

create table public.wa_instance_status (
    id bigint generated by default as identity primary key,
    instance text not null unique,
    connected boolean not null default false,
    last_event jsonb,
    updated_at timestamp with time zone not null default now()
);

-- send_queue (10_) was born for quotes only (deal and quote mandatory). A text
-- written in the inbox has no quote and its conversation may have no lead, so
-- a queue row now targets either a quote (with its lead, as before) or one
-- wa_messages row over WhatsApp (docs/10). Altered here, not in 10_: the
-- foreign key needs wa_messages, which is created in this file.
alter table public.send_queue
    alter column deal_id drop not null,
    alter column quote_id drop not null,
    add column message_id bigint references public.wa_messages (id) on delete restrict,
    add constraint send_queue_message_key unique (message_id),
    add constraint send_queue_target_check check (
        (quote_id is not null and deal_id is not null and message_id is null)
        or (quote_id is null and message_id is not null and channel = 'whatsapp'));

alter table public.wa_conversations enable row level security;
alter table public.wa_messages enable row level security;
alter table public.wa_instance_status enable row level security;
alter table public.wa_message_payloads enable row level security;

create index wa_messages_conversation_sent_idx on public.wa_messages using btree (conversation_id, sent_at);
create index wa_messages_deal_id_idx on public.wa_messages using btree (deal_id);
-- send_wa_message counts the caller's recent texts on every call (rate limit).
create index wa_messages_author_created_idx on public.wa_messages using btree (author_sales_id, created_at);
-- sales_id: the executive's RLS filter and "Mis chats"; last_message_at: inbox order.
create index wa_conversations_sales_id_idx on public.wa_conversations using btree (sales_id);
create index wa_conversations_last_message_at_idx on public.wa_conversations using btree (last_message_at desc);

-- Policies (docs/08, row "conversaciones, mensajes"). Select only: no insert,
-- update or delete policy on purpose (service role and RPCs write; nothing is
-- ever deleted, docs/10 decision 3). Helpers go through `(select fn())` as in
-- deals_select (11_). Unlike deals, the role is checked on the executive
-- branch too: a reader that still owns a conversation (demoted) sees none.
create policy wa_conversations_select on public.wa_conversations for select to authenticated using (
    (select public.is_manager())
    or ((select public.current_user_role()) = 'executive'
        and (sales_id = (select public.current_sales_id()) or sales_id is null))
);
-- A message is visible when its conversation is (the subquery runs under the
-- wa_conversations RLS of the caller, like deal_notes_select).
create policy wa_messages_select on public.wa_messages for select to authenticated
    using (exists (select 1 from public.wa_conversations c where c.id = conversation_id));

-- Realtime (docs/07, Bandeja): the inbox listens to postgres_changes on these
-- two tables. Realtime delivers a row only to subscribers whose role and JWT
-- pass the select policies above, so the policies stay the single gate.
-- wa_message_payloads and wa_instance_status are never published (docs/10).
-- migra does not diff publications: the migration is written by hand.
alter publication supabase_realtime add table public.wa_conversations, public.wa_messages;

--
-- Ingest (docs/07, Receptor). Only the service role (Edge Function) calls
-- these. Ingesting a message is one atomic function so that a webhook retry
-- (same wa_message_id) changes nothing: the conversation counters move only
-- when the message row was actually inserted (docs/10).
--
-- An outgoing message without job_id was written from the phone, not from the
-- CRM or a followup: it is attributed to the executive owning the conversation.
-- p_instance is not stored yet (there is a single corporate number).
--
CREATE OR REPLACE FUNCTION "public"."wa_ingest_message"("p_instance" "text", "p_wa_message_id" "text", "p_phone" "text", "p_direction" "public"."wa_direction", "p_type" "public"."wa_message_type", "p_text" "text", "p_sent_at" timestamp with time zone, "p_payload" "jsonb", "p_job_id" "text" DEFAULT NULL::"text") RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  v_conversation public.wa_conversations;
  v_message_id bigint;
  v_from_phone boolean := p_direction = 'saliente' and p_job_id is null;
begin
  -- The no-op update locks the conversation row: concurrent messages of the
  -- same number serialize here and unread_count never loses an increment.
  insert into public.wa_conversations (phone) values (p_phone)
  on conflict (phone) do update set phone = excluded.phone
  returning * into v_conversation;

  insert into public.wa_messages (conversation_id, deal_id, wa_message_id, direction, type, text, sent_at, job_id, origin, from_me_phone, author_sales_id)
  values (v_conversation.id, v_conversation.active_deal_id, p_wa_message_id, p_direction, p_type, p_text, p_sent_at, p_job_id,
          case when v_from_phone then 'telefono'::public.wa_message_origin end,
          v_from_phone,
          case when v_from_phone then v_conversation.sales_id end)
  on conflict (wa_message_id) do nothing
  returning id into v_message_id;

  if v_message_id is null then
    select m.id into v_message_id from public.wa_messages m where m.wa_message_id = p_wa_message_id;
    return jsonb_build_object('conversation_id', v_conversation.id, 'message_id', v_message_id, 'inserted', false);
  end if;

  if p_payload is not null then
    insert into public.wa_message_payloads (message_id, payload) values (v_message_id, p_payload);
  end if;

  update public.wa_conversations
  set last_message_at = greatest(last_message_at, p_sent_at),
      unread_count = unread_count + case when p_direction = 'entrante' then 1 else 0 end
  where id = v_conversation.id;

  return jsonb_build_object('conversation_id', v_conversation.id, 'message_id', v_message_id, 'inserted', true);
end;
$$;

-- Status never goes back: pendiente < enviado < entregado < leido (enum
-- order); fallido only from pendiente or enviado. Returns whether it changed.
CREATE OR REPLACE FUNCTION "public"."wa_update_message_status"("p_wa_message_id" "text", "p_status" "public"."delivery_status") RETURNS boolean
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  update public.wa_messages m
  set status = p_status
  where m.wa_message_id = p_wa_message_id
    and case when p_status = 'fallido' then m.status in ('pendiente', 'enviado')
             else m.status < p_status end;
  return found;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."wa_upsert_instance_status"("p_instance" "text", "p_connected" boolean, "p_event" "jsonb") RETURNS "void"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  insert into public.wa_instance_status (instance, connected, last_event, updated_at)
  values (p_instance, p_connected, p_event, now())
  on conflict (instance) do update
  set connected = excluded.connected, last_event = excluded.last_event, updated_at = now();
end;
$$;

--
-- Inbox RPCs (docs/07, Bandeja). Same pattern as take_deal (11_): the tables
-- are read-only for users, so these security definer functions are the only
-- way the inbox writes. Errors: 42501 without permission, P0002 when the
-- conversation does not exist or is not available.
--
-- Take an unassigned, not archived conversation for the caller.
CREATE OR REPLACE FUNCTION "public"."take_wa_conversation"("conversation_id" bigint) RETURNS "public"."wa_conversations"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  me bigint := public.current_sales_id();
  taken public.wa_conversations;
begin
  if me is null or public.current_user_role() not in ('manager', 'executive') then
    raise exception 'only executives and managers can take a conversation' using errcode = '42501';
  end if;
  update public.wa_conversations c
     set sales_id = me
   where c.id = take_wa_conversation.conversation_id and c.sales_id is null and not c.archived
   returning * into taken;
  if not found then
    raise exception 'conversation % is not available', take_wa_conversation.conversation_id using errcode = 'P0002';
  end if;
  return taken;
end;
$$;

-- Mark the incoming messages of a conversation as read; returns how many
-- changed. An unassigned conversation is left untouched (returns 0, also for
-- managers) so it keeps showing as new until someone takes it (docs/10).
CREATE OR REPLACE FUNCTION "public"."mark_wa_conversation_read"("conversation_id" bigint) RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  me bigint := public.current_sales_id();
  my_role text := public.current_user_role();
  owner bigint;
  marked integer;
begin
  if me is null or my_role not in ('manager', 'executive') then
    raise exception 'only executives and managers can read conversations' using errcode = '42501';
  end if;
  select c.sales_id into owner
    from public.wa_conversations c
   where c.id = mark_wa_conversation_read.conversation_id
     for update;
  if not found then
    raise exception 'conversation % does not exist', mark_wa_conversation_read.conversation_id using errcode = 'P0002';
  end if;
  if owner is null then
    return 0;
  end if;
  if my_role <> 'manager' and owner <> me then
    raise exception 'conversation % belongs to another executive', mark_wa_conversation_read.conversation_id using errcode = '42501';
  end if;
  update public.wa_messages m
     set status = 'leido'
   where m.conversation_id = mark_wa_conversation_read.conversation_id
     and m.direction = 'entrante' and m.status <> 'leido';
  get diagnostics marked = row_count;
  update public.wa_conversations c
     set unread_count = 0
   where c.id = mark_wa_conversation_read.conversation_id;
  return marked;
end;
$$;

-- Write a text from the inbox. Nothing is sent here: the message is stored as
-- 'pendiente' and enqueued in send_queue (channel whatsapp, like send_quote in
-- 11_); the sender (whatsapp-send) takes it from there. Executives only in
-- their own conversations, managers (aal2, through current_user_role()) in
-- any; readers and everyone else get 42501. Archived conversation: P0002 (as
-- take_wa_conversation). Empty or too long text: 22023. More than
-- max_messages_per_window texts by the same user within rate_window: PT429
-- (PostgREST answers HTTP 429).
-- wa_message_id is provisional ('pending:' || job_id): the sender replaces it
-- with the id Evolution returns (docs/10).
CREATE OR REPLACE FUNCTION "public"."send_wa_message"("conversation_id" bigint, "text" "text") RETURNS "public"."wa_messages"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  -- Longest text body WhatsApp accepts in one message.
  max_text_length constant integer := 4096;
  -- Cap of texts one user writes from the CRM (a runaway client, not the
  -- anti-block pacing, which belongs to the sender: docs/07).
  max_messages_per_window constant integer := 30;
  rate_window constant interval := interval '1 minute';
  me bigint := public.current_sales_id();
  my_role text := public.current_user_role();
  body text := btrim(send_wa_message.text, E' \t\n\r');
  job text := 'crm-' || gen_random_uuid()::text;
  conv public.wa_conversations;
  msg public.wa_messages;
  recent integer;
begin
  if me is null or my_role not in ('manager', 'executive') then
    raise exception 'only executives and managers can send messages' using errcode = '42501';
  end if;
  select * into conv
    from public.wa_conversations c
   where c.id = send_wa_message.conversation_id
     for update;
  if not found then
    raise exception 'conversation % does not exist', send_wa_message.conversation_id using errcode = 'P0002';
  end if;
  if my_role <> 'manager' and conv.sales_id is distinct from me then
    raise exception 'conversation % is not assigned to you', conv.id using errcode = '42501';
  end if;
  if conv.archived then
    raise exception 'conversation % is archived', conv.id using errcode = 'P0002';
  end if;
  if body is null or body = '' then
    raise exception 'the message text is empty' using errcode = '22023';
  end if;
  if char_length(body) > max_text_length then
    raise exception 'the message text is longer than % characters', max_text_length using errcode = '22023';
  end if;
  -- One sender at a time per user: without it, parallel calls on different
  -- conversations would each count before the others commit and go over the cap.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('send_wa_message:' || me, 0));
  select count(*) into recent
    from public.wa_messages m
   where m.author_sales_id = me and m.origin = 'crm' and m.created_at > now() - rate_window;
  if recent >= max_messages_per_window then
    raise exception 'rate limit: at most % messages per minute', max_messages_per_window using errcode = 'PT429';
  end if;

  insert into public.wa_messages (conversation_id, deal_id, wa_message_id, direction, type, text, status, origin, author_sales_id, job_id, sent_at)
  values (conv.id, conv.active_deal_id, 'pending:' || job, 'saliente', 'texto', body, 'pendiente', 'crm', me, job, now())
  returning * into msg;

  insert into public.send_queue (deal_id, message_id, channel, sales_id)
  values (conv.active_deal_id, msg.id, 'whatsapp', me);

  update public.wa_conversations c
     set last_message_at = greatest(c.last_message_at, msg.sent_at)
   where c.id = conv.id;
  return msg;
end;
$$;

-- Connection indicator (docs/07): the one thing a logged-in user (any role)
-- learns about the instance. wa_instance_status stays closed because
-- last_event keeps raw Evolution bodies (instance apikey): this function
-- returns connected and updated_at only, never last_event. There is a single
-- corporate number; with several rows the most recently updated one counts.
-- No row yet: connected false, updated_at null.
CREATE OR REPLACE FUNCTION "public"."wa_connection_status"() RETURNS TABLE("connected" boolean, "updated_at" timestamp with time zone)
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select coalesce(s.connected, false), s.updated_at
    from (values (1)) one (n)
    left join lateral (
      select i.connected, i.updated_at
        from public.wa_instance_status i
       order by i.updated_at desc, i.id desc
       limit 1) s on true;
$$;

-- tg_mensaje_entrante (docs/05, CLAUDE.md §1.4): a client message on a lead
-- cancels its pending followups and alerts the lead owner (no owner, no
-- alert). A webhook retry inserts nothing, so it fires nothing. An already
-- open cliente_respondio alert for the same lead is not repeated
-- (alerts_open_key).
CREATE OR REPLACE FUNCTION "public"."wa_cliente_respondio"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  d public.deals;
begin
  update public.followups f
     set status = 'cancelado', cancel_reason = 'Cliente respondió por WhatsApp'
   where f.deal_id = new.deal_id and f.status = 'pendiente';

  select * into d from public.deals where id = new.deal_id;
  if d.sales_id is not null then
    insert into public.alerts (type, recipient_sales_id, deal_id, message)
    values ('cliente_respondio', d.sales_id, d.id, format('El cliente respondió por WhatsApp en el lead «%s»', d.name))
    on conflict do nothing;
  end if;
  return null;
end;
$$;

CREATE OR REPLACE TRIGGER "wa_cliente_respondio" AFTER INSERT ON "public"."wa_messages" FOR EACH ROW WHEN ((("new"."direction" = 'entrante'::"public"."wa_direction") AND ("new"."deal_id" IS NOT NULL))) EXECUTE FUNCTION "public"."wa_cliente_respondio"();

-- Grants live here (not in 12_): schema files load alphabetically, so 12_
-- runs before these tables exist. Default privileges would hand authenticated
-- full DML: close them to the API roles; only the service role writes.
-- authenticated gets select alone on conversations and messages (the policies
-- above filter the rows); wa_instance_status and wa_message_payloads stay
-- without any privilege.
revoke all on table public.wa_conversations, public.wa_messages, public.wa_instance_status, public.wa_message_payloads from authenticated, anon;
grant select on table public.wa_conversations, public.wa_messages to authenticated;
grant all on table public.wa_conversations, public.wa_messages, public.wa_instance_status, public.wa_message_payloads to service_role;
revoke all on sequence public.wa_conversations_id_seq, public.wa_messages_id_seq, public.wa_instance_status_id_seq from authenticated, anon;
grant all on sequence public.wa_conversations_id_seq, public.wa_messages_id_seq, public.wa_instance_status_id_seq to service_role;
revoke execute on function public.wa_ingest_message(text, text, text, public.wa_direction, public.wa_message_type, text, timestamp with time zone, jsonb, text) from public, anon, authenticated;
grant execute on function public.wa_ingest_message(text, text, text, public.wa_direction, public.wa_message_type, text, timestamp with time zone, jsonb, text) to service_role;
revoke execute on function public.wa_update_message_status(text, public.delivery_status) from public, anon, authenticated;
grant execute on function public.wa_update_message_status(text, public.delivery_status) to service_role;
revoke execute on function public.wa_upsert_instance_status(text, boolean, jsonb) from public, anon, authenticated;
grant execute on function public.wa_upsert_instance_status(text, boolean, jsonb) to service_role;
-- Inbox RPCs: logged-in users only (they need a sales row; the service role has none).
revoke execute on function public.take_wa_conversation(bigint) from public, anon, service_role;
