-- Outgoing queue (Fase 3): one row per channel for each quote the CRM asks to
-- send. n8n (Fase 5) sends it and updates status; the CRM only enqueues
-- through send_quote(). Never deleted.
create table public.send_queue (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    deal_id bigint not null references public.deals (id) on delete restrict,
    quote_id bigint not null references public.quotes (id) on delete restrict,
    channel public.send_channel not null,
    status public.delivery_status not null default 'pendiente',
    sales_id bigint references public.sales (id) on delete restrict,
    sent_at timestamp with time zone,
    attempts smallint not null default 0,
    error text,
    constraint send_queue_quote_channel_key unique (quote_id, channel),
    constraint send_queue_attempts_positive check (attempts >= 0)
);

alter table public.send_queue enable row level security;

create index send_queue_deal_id_idx on public.send_queue using btree (deal_id);
create index send_queue_sales_id_idx on public.send_queue using btree (sales_id);
-- n8n's queue: pending rows in arrival order.
create index send_queue_pending_idx on public.send_queue using btree (created_at) where status = 'pendiente';

