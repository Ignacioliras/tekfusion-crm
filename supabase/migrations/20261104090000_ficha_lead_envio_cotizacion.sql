-- Stage and owner changes made by users go to audit_log, which feeds the lead
-- timeline. Only API sessions are logged: offboard_sale (service role) and
-- n8n write their own entries. Security definer: users cannot insert into
-- audit_log themselves.
CREATE OR REPLACE FUNCTION "public"."log_deal_changes"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  actor bigint := public.current_sales_id();
begin
  if auth.role() is distinct from 'authenticated' then
    return new;
  end if;
  if new.stage is distinct from old.stage then
    insert into public.audit_log (actor_sales_id, action, deal_id, details)
    values (actor, 'deal.stage_changed', new.id, jsonb_build_object('from', old.stage, 'to', new.stage));
  end if;
  if new.sales_id is distinct from old.sales_id then
    insert into public.audit_log (actor_sales_id, action, target_sales_id, deal_id, details)
    values (actor, 'deal.reassigned', new.sales_id, new.id, jsonb_build_object('from', old.sales_id, 'to', new.sales_id));
  end if;
  return new;
end;
$$;

create or replace trigger log_deal_changes_trigger
    after update of stage, sales_id on public.deals
    for each row execute function public.log_deal_changes();

-- Moving a lead to ganado requires the final amount; to perdido, a reason
-- (RF-04). Only on the transition: leads imported already closed (RF-15,
-- historical data) may lack them.
CREATE OR REPLACE FUNCTION "public"."guard_deal_closing"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if new.stage is distinct from old.stage then
    if new.stage = 'ganado' and new.won_amount is null then
      raise exception 'a won lead needs its final amount' using errcode = '23514';
    end if;
    if new.stage = 'perdido' and new.lost_reason_id is null then
      raise exception 'a lost lead needs a reason' using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

create or replace trigger guard_deal_closing_trigger
    before update of stage on public.deals
    for each row execute function public.guard_deal_closing();

-- A new quote gets the next version and replaces the current one, which
-- stays in the history (RF-06).
CREATE OR REPLACE FUNCTION "public"."set_quote_version"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if new.version is null then
    select coalesce(max(q.version), 0) + 1 into new.version from public.quotes q where q.deal_id = new.deal_id;
  end if;
  if new.is_current then
    update public.quotes set is_current = false where deal_id = new.deal_id and is_current;
  end if;
  return new;
end;
$$;

create or replace trigger set_quote_version_trigger
    before insert on public.quotes
    for each row execute function public.set_quote_version();

-- "Enviar cotización" (RF-06): enqueues the current quote on the chosen
-- channels (n8n sends it, Fase 5), moves the lead to cotizado, cancels the
-- pending follow-ups and schedules the default cadence
-- (configuration.config.followupCadenceDays, default [2, 5, 10]) at 10:00
-- Santiago, moved off weekends. Security definer: users cannot write the
-- queue; the caller must be a manager or the lead's executive.
CREATE OR REPLACE FUNCTION "public"."send_quote"("quote_id" bigint, "channels" "public"."send_channel"[]) RETURNS "public"."quotes"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  q public.quotes;
  d public.deals;
  me bigint := public.current_sales_id();
  cadence jsonb;
  days int;
  step int := 0;
  due timestamp with time zone;
begin
  select * into q from public.quotes where id = quote_id for update;
  if not found then
    raise exception 'quote % does not exist', quote_id using errcode = 'P0002';
  end if;
  if not public.can_edit_deal(q.deal_id) then
    raise exception 'only managers and the lead owner can send its quote' using errcode = '42501';
  end if;
  if coalesce(cardinality(channels), 0) = 0 then
    raise exception 'choose at least one channel' using errcode = '22023';
  end if;
  if not q.is_current then
    raise exception 'only the current quote can be sent' using errcode = '22023';
  end if;
  if exists (select 1 from public.send_queue s where s.quote_id = q.id) then
    raise exception 'quote % was already sent', q.id using errcode = '23505';
  end if;
  select * into d from public.deals where id = q.deal_id for update;
  if d.stage not in ('nuevo', 'contactado', 'cotizado') or d.archived_at is not null then
    raise exception 'lead % is closed', d.id using errcode = '22023';
  end if;

  insert into public.send_queue (deal_id, quote_id, channel, sales_id)
  select d.id, q.id, c, coalesce(d.sales_id, me) from (select distinct unnest(channels) as c) ch;

  update public.quotes set sent_channels = (select array_agg(distinct c) from unnest(channels) c), delivery_status = 'pendiente'
   where id = q.id returning * into q;

  update public.deals
     set stage = 'cotizado', amount = q.amount, updated_at = now(), last_activity_at = now(),
         first_response_at = coalesce(first_response_at, now())
   where id = d.id;

  update public.followups set status = 'cancelado', cancel_reason = 'Nueva cotización enviada'
   where deal_id = d.id and status in ('pendiente', 'vencido');

  if d.followups_enabled then
    select coalesce(c.config -> 'followupCadenceDays', '[2, 5, 10]'::jsonb) into cadence
      from public.configuration c where c.id = 1;
    for days in select jsonb_array_elements_text(coalesce(cadence, '[2, 5, 10]'::jsonb))::int loop
      step := step + 1;
      due := ((now() at time zone 'America/Santiago')::date + days + time '10:00') at time zone 'America/Santiago';
      due := due + (case extract(isodow from due at time zone 'America/Santiago')
                      when 6 then 2 when 7 then 1 else 0 end) * interval '1 day';
      insert into public.followups (deal_id, step, scheduled_at, channels, mode, template_id)
      values (d.id, step, due, (select array_agg(distinct c) from unnest(channels) c), 'automatico',
              (select t.id from public.templates t
                where t.active and t.channel = channels[1]
                order by t.id
                offset (step - 1) % greatest((select count(*) from public.templates t2 where t2.active and t2.channel = channels[1]), 1)
                limit 1));
    end loop;
  end if;
  return q;
end;
$$;

create policy send_queue_select on public.send_queue for select to authenticated
    using (exists (select 1 from public.deals d where d.id = deal_id));

-- The lead timeline reads the audit rows of the leads the user can see
-- (managers keep reading everything through audit_log_select).
create policy audit_log_select_deal on public.audit_log for select to authenticated
    using (deal_id is not null and (select public.is_internal_user())
        and exists (select 1 from public.deals d where d.id = deal_id));

