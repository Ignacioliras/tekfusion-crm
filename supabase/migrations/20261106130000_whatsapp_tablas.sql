-- Fase 4: tablas de WhatsApp (solo esquema; supabase/schemas/14_tekfusion_whatsapp.sql).
-- Generada con `db diff` y revisada a mano: se quitaron los drop de pg_cron y
-- pgjwt y la recreación de vistas sin cambios (las dejaba sin security_invoker),
-- y se agregaron los revokes/grants que migra no emite. RLS activa sin
-- policies: solo el service role lee y escribe.

create type "public"."wa_direction" as enum ('entrante', 'saliente');

create type "public"."wa_message_origin" as enum ('crm', 'seguimiento', 'telefono');

create type "public"."wa_message_type" as enum ('texto', 'imagen', 'documento', 'audio', 'video', 'otro');

create table "public"."wa_conversations" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamp with time zone not null default now(),
    "phone" text not null unique,
    "contact_id" bigint references public.contacts (id) on delete set null,
    "active_deal_id" bigint references public.deals (id) on delete set null,
    "sales_id" bigint references public.sales (id) on delete set null,
    "last_message_at" timestamp with time zone,
    "unread_count" integer not null default 0,
    "archived" boolean not null default false,
    constraint "wa_conversations_phone_e164" check (phone ~ '^\+[1-9][0-9]{7,14}$'),
    constraint "wa_conversations_unread_count_positive" check (unread_count >= 0)
);

create table "public"."wa_messages" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamp with time zone not null default now(),
    "conversation_id" bigint not null references public.wa_conversations (id) on delete restrict,
    "deal_id" bigint references public.deals (id) on delete set null,
    "wa_message_id" text not null unique,
    "direction" public.wa_direction not null,
    "type" public.wa_message_type not null,
    "text" text,
    "attachment_path" text,
    "status" public.delivery_status not null default 'pendiente'::public.delivery_status,
    "from_me_phone" boolean not null default false,
    "author_sales_id" bigint references public.sales (id) on delete set null,
    "origin" public.wa_message_origin,
    "job_id" text unique,
    "payload" jsonb,
    "sent_at" timestamp with time zone not null
);

create table "public"."wa_instance_status" (
    "id" bigint generated by default as identity primary key,
    "instance" text not null unique,
    "connected" boolean not null default false,
    "last_event" jsonb,
    "updated_at" timestamp with time zone not null default now()
);

alter table "public"."wa_conversations" enable row level security;
alter table "public"."wa_messages" enable row level security;
alter table "public"."wa_instance_status" enable row level security;

create index wa_messages_conversation_sent_idx on public.wa_messages using btree (conversation_id, sent_at);
create index wa_messages_deal_id_idx on public.wa_messages using btree (deal_id);

revoke all on table public.wa_conversations, public.wa_messages, public.wa_instance_status from authenticated, anon;
grant all on table public.wa_conversations, public.wa_messages, public.wa_instance_status to service_role;
revoke all on sequence public.wa_conversations_id_seq, public.wa_messages_id_seq, public.wa_instance_status_id_seq from authenticated, anon;
grant all on sequence public.wa_conversations_id_seq, public.wa_messages_id_seq, public.wa_instance_status_id_seq to service_role;
